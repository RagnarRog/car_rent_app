class Car {
  final String id;
  final String modelName;
  final String imageUrl;
  final String price;
  final String userId;
  final int phone;
  final String info;
  final String fuelType;

  Car({
    required this.id,
    required this.modelName,
    required this.imageUrl,
    required this.price,
    required this.phone,
    required this.info,
    required this.fuelType,
    required this.userId,
  });
}
